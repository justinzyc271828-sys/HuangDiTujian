def main():
    results = []
    # expand existing
    for pid, addons in ADDONS.items():
        existing = list_existing(pid)
        n0 = len(existing)
        # next index
        max_i = 0
        for eid, *_ in existing:
            try:
                max_i = max(max_i, int(eid.replace("E", "")))
            except ValueError:
                pass
        added = 0
        for ev in addons:
            if n0 + added >= 12:
                break
            idx = max_i + 1 + added
            if write_card(pid, idx, ev):
                added += 1
        # display name from dossier or id
        display = pid
        dpath = SRC / pid / "00-史源卡.md"
        if dpath.exists():
            for line in dpath.read_text(encoding="utf-8").splitlines():
                if line.startswith("display_name:"):
                    display = line.split(":", 1)[1].strip().strip('"')
                    break
        # meta scraps from old dossier dynasties
        st, n = refresh_dossier(pid, display, {"dynasty": "", "personal": ""})
        results.append((pid, n0, n, added, st))
        print(f"expand {pid}: {n0} -> {n} (+{added}) {st}")

    for pid, pack in NEW_PEOPLE.items():
        st, n = scaffold_new(pid, pack)
        results.append((pid, 0, n, n, st))
        print(f"new {pid}: {n} {st}")

    # update sources README
    lines = [
        "# 史源 / 史料工作区",
        "",
        "规范：`docs/05-史源卡工作规范.md`  · 看板：`docs/08-项目进度看板.md`",
        "",
        "## 状态总览（expand-dossier 后）",
        "",
        "| id | status | 史料卡 |",
        "|----|--------|--------|",
    ]
    for d in sorted(SRC.iterdir()):
        if not d.is_dir() or d.name.startswith("_"):
            continue
        if not (d / "00-史源卡.md").exists():
            continue
        st = "?"
        for line in (d / "00-史源卡.md").read_text(encoding="utf-8").splitlines()[:12]:
            if line.startswith("status:"):
                st = line.split(":", 1)[1].strip()
            if line.startswith("display_name:"):
                pass
        n = len([p for p in (d / "证据").glob("E*.md") if p.name != "_template.md"]) if (d / "证据").exists() else 0
        lines.append(f"| {d.name} | {st} | {n} |")
    lines += ["", "新建：`han-gao-zu` · `qin-er-shi`（原有 YAML、补 sources）", ""]
    (SRC / "README.md").write_text("\n".join(lines), encoding="utf-8")
    print("done", len(results))


if __name__ == "__main__":
    main()

def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--only", default="", help="comma-separated ids")
    args = ap.parse_args()
    only = {x.strip() for x in args.only.split(",") if x.strip()}

    total = 0
    for pid, pack in DOSSIERS.items():
        if only and pid not in only:
            continue
        n = write_dossier(pid, pack)
        total += n
        print(f"OK {pid} {n}")

    # refresh sources README counts
    from collections import Counter

    stc: Counter[str] = Counter()
    cards = 0
    for d in SRC.iterdir():
        if not d.is_dir() or d.name.startswith("_") or not (d / "00-史源卡.md").exists():
            continue
        st = "?"
        for line in (d / "00-史源卡.md").read_text(encoding="utf-8").splitlines()[:12]:
            if line.startswith("status:"):
                st = line.split(":", 1)[1].strip()
                break
        stc[st] += 1
        cards += len([p for p in (d / "证据").glob("E*.md") if p.name != "_template.md"])
    print("STATUS", dict(stc), "CARDS", cards, "UPGRADED_BATCH", total)


if __name__ == "__main__":
    main()
